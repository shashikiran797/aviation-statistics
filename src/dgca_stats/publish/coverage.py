"""Data-status summary: which datasets are scraped and the latest period of each.

Computed at publish time from the published fact tables, stored in catalog.json (shown in the app's
"Data sources & coverage" panel) and rendered into the README between STATUS markers.
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

QUARTERLY = {"intl_country_quarterly", "intl_citypair_quarterly"}
START, END = "<!-- DATA-STATUS:START (generated by `dgca publish`, do not edit) -->", "<!-- DATA-STATUS:END -->"


def _label(key: int, quarterly: bool) -> str:
    y, m = divmod(int(key), 100)
    if quarterly:    # quarters are keyed by their first month; reported as calendar quarters
        return f"Q{(m - 1) // 3 + 1} {y}"
    return pd.Timestamp(y, m, 1).strftime("%b %Y")


def compute(tables: dict, facts: dict, man: pd.DataFrame, site_stats: dict, site_files: pd.DataFrame | None) -> dict:
    ok = man[man.parse_status == "ok"]
    datasets = []
    for fid, f in facts.items():
        t = tables[f["table"]]
        q = fid in QUARTERLY
        lo, hi = int(t.period_key.min()), int(t.period_key.max())
        latest = t[t.period_key == hi]
        prov = bool(latest["provisional"].any()) if "provisional" in latest else False
        datasets.append({"id": fid, "label": f["label"], "grain": f["grain"], "rows": int(len(t)),
                         "first": _label(lo, q), "latest": _label(hi, q), "latest_key": hi,
                         "latest_provisional": prov, "granularity": "quarterly" if q else "monthly"})
    unused = {}
    if site_files is not None and len(site_files):
        s = site_files[~site_files.in_dashboards.astype(bool)]
        unused = {"files_not_in_dashboards": int(len(s)), "files_total": int(len(site_files))}
    return {
        "last_crawled": str(man.last_seen.max()) if "last_seen" in man and man.last_seen.notna().any() else None,
        "source_files_parsed": int(len(ok)),
        "newest_source_modified": _newest(ok.get("last_modified")),
        "datasets": datasets,
        "portal": {**unused, "files": site_stats.get("files"), "tables": site_stats.get("tables")},
    }


def _newest(s) -> str | None:
    if s is None:
        return None
    d = pd.to_datetime(s, errors="coerce", utc=True).dropna()
    return d.max().strftime("%Y-%m-%d") if len(d) else None


def markdown(cov: dict) -> str:
    rows = ["| Dataset | Grain | Rows | First | Latest period |", "|---|---|---:|---|---|"]
    for d in cov["datasets"]:
        late = d["latest"] + (" (provisional)" if d["latest_provisional"] else "")
        rows.append(f"| `{d['id']}` | {d['grain'].replace('|', '/')} | {d['rows']:,} | {d['first']} | **{late}** |")
    crawled = (cov["last_crawled"] or "?")[:10]
    p = cov["portal"]
    tail = (f"\nLast crawl of the DGCA portal: **{crawled}**; {cov['source_files_parsed']} statistics files parsed"
            f", newest source file modified {cov['newest_source_modified']}. "
            f"The portal catalog lists {p.get('files', 0):,} files, of which {p.get('files_not_in_dashboards', 0):,} "
            "(fleet, personnel, financial, older years, PDFs, other sections) are catalogued but not yet in the dashboards.\n")
    return "\n".join(rows) + "\n" + tail


def update_readme(path: Path, cov: dict) -> bool:
    s = path.read_text()
    block = f"{START}\n{markdown(cov)}{END}"
    if START in s:
        new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, s, flags=re.S)
    else:
        return False
    if new != s:
        path.write_text(new)
    return True
